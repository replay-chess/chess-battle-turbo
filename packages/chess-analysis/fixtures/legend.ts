// Loader for the legend comparison fixtures in `fixtures/legend/*.json` (phase-03 plan §8.9 "Fixtures", §12.4
// `legend/*.json`): the Opera Game (2 of 3, then 12.Ba4 for 12.O-O-O), Kasparov–Topalov (27.Qc3+ for 27.b4+), the
// opponent leaving the line first, a game that follows the legend to its final move, and a legend score shorter
// than the game.
//
// Each file holds the legend's PGN (historical game scores, public domain), the legend position, the member's colour
// and the member's game as SAN from that position, and the facts and screen texts expected from them, written by
// hand from the moves (not generated by the code under test). `legendLinePrefix`/`legendLinePlies` stand in for the
// full legend line where it is long (Kasparov–Topalov runs 41 plies from move 24).

import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Chess } from "chess.js";
import { compareWithLegend, type ComparisonFacts } from "../src/legend/compare";
import { legendLineFrom, legendResultOf, startPlyOfFen, type MemberOutcome } from "../src/legend/slice";
import type { LineRow, SummaryRow } from "../src/legend/summary";

export interface LegendFixture {
  name: string;
  provenance: string;
  note: string;
  legendPgn: string;
  metadata: Record<string, unknown> | null;
  historicalName: string;
  opponentHistoricalName: string | null;
  year: number | null;
  startFen: string;
  member: "w" | "b";
  userResult: MemberOutcome | null;
  /** The member's game from startFen, SAN. */
  game: string[];
  expected: {
    facts: Omit<ComparisonFacts, "legendLineUci"> & { legendLineUci?: string };
    legendLinePrefix?: string;
    legendLinePlies?: number;
    followedToTheEnd: boolean;
    summaryLine: string;
    matchedLine: string;
    outcomeLine: string;
    paragraph: string;
    paragraphWithEvals?: { evalAtDivergence: { userWin: number; legendWin: number }; text: string };
    replayHref: string | null;
    rows: SummaryRow[];
    yourLineRows?: LineRow[];
  };
}

export const LEGEND_FIXTURE_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "legend");
/** The game ref the fixtures' replay links use. */
export const LEGEND_FIXTURE_REF = "fixture-ref";

export function loadLegendFixtures(): LegendFixture[] {
  return readdirSync(LEGEND_FIXTURE_DIR)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => JSON.parse(readFileSync(path.join(LEGEND_FIXTURE_DIR, f), "utf8")) as LegendFixture);
}

export function legendFixture(name: string): LegendFixture {
  const f = loadLegendFixtures().find((x) => x.name === name);
  if (!f) throw new Error(`no legend fixture ${name}`);
  return f;
}

/** The fixture game's moves as UCI. */
export function legendFixtureMoves(f: LegendFixture): string[] {
  const c = new Chess(f.startFen);
  return f.game.map((san) => {
    const m = c.move(san);
    return `${m.from}${m.to}${m.promotion ?? ""}`;
  });
}

/** compareWithLegend on a fixture, the way every writer calls it (slice the PGN, read the result, compare). */
export function legendFixtureFacts(f: LegendFixture): ComparisonFacts {
  const line = legendLineFrom(f.legendPgn, f.startFen);
  if (!line) throw new Error(`${f.name}: the legend PGN does not reach the start position`);
  const result = legendResultOf(f.legendPgn, f.metadata);
  if (!result) throw new Error(`${f.name}: the legend result is unknown`);
  return compareWithLegend({
    startFen: f.startFen,
    startPly: startPlyOfFen(f.startFen),
    moves: legendFixtureMoves(f),
    member: f.member,
    legendUci: line.uci,
    historicalName: f.historicalName,
    legendResult: result,
    legendTotalMoves: line.totalMoves,
  });
}
