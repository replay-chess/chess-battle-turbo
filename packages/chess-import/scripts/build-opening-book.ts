/**
 * Builds `src/opening-book.data.ts`, the opening book as UCI move lines, from the TSVs the `openings` table is seeded
 * from (`apps/web/public/openings/*.tsv`, eco<TAB>name<TAB>pgn; packages/db/prisma/opening-seed.ts). Each line is
 * replayed with chess.js from the initial position; a line that does not replay is left out and reported. Two lines
 * with the same moves keep the first in file order (a.tsv … e.tsv, the seed's insert order). The data lets an
 * imported game be named from its moves (`src/opening-name.ts`) without chess.js or a database at lookup time.
 * `src/__tests__/opening-name.test.ts` fails when the committed data and the TSVs disagree.
 *
 *   pnpm --filter @repo/chess-import exec tsx scripts/build-opening-book.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Chess } from "chess.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const OPENINGS_DIR = path.resolve(HERE, "../../../apps/web/public/openings");
const OUT = path.resolve(HERE, "../src/opening-book.data.ts");

export type BookEntry = readonly [eco: string, name: string, uci: string];

/** The TSV texts of the book, in seed order. */
export function readOpeningTsvs(dir = OPENINGS_DIR): string[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".tsv"))
    .sort()
    .map((f) => readFileSync(path.join(dir, f), "utf8"));
}

/** Book lines as `[eco, name, uci]`, first line per move sequence, plus the lines that did not replay. */
export function bookEntriesOf(tsvs: readonly string[]): { entries: BookEntry[]; failures: string[] } {
  const entries: BookEntry[] = [];
  const failures: string[] = [];
  const seen = new Set<string>();
  for (const tsv of tsvs) {
    for (const row of tsv.split(/\r?\n/).slice(1)) {
      if (row.trim() === "") continue;
      const [eco, name, pgn] = row.split("\t").map((c) => c.trim());
      if (!eco || !name || !pgn || !/^[A-E]\d\d$/.test(eco)) continue;
      const chess = new Chess();
      const uci: string[] = [];
      let ok = true;
      for (const tok of pgn.split(/\s+/)) {
        const san = tok.replace(/^\d+\.(\.\.)?/, "");
        if (san === "" || /^(1-0|0-1|1\/2-1\/2|\*)$/.test(san)) continue;
        try {
          const m = chess.move(san);
          uci.push(`${m.from}${m.to}${m.promotion ?? ""}`);
        } catch {
          ok = false;
          break;
        }
      }
      if (!ok || uci.length === 0) {
        failures.push(`${eco} ${name}: ${pgn}`);
        continue;
      }
      const key = uci.join(" ");
      if (seen.has(key)) continue;
      seen.add(key);
      entries.push([eco, name, key]);
    }
  }
  return { entries, failures };
}

export function renderBookData(entries: readonly BookEntry[]): string {
  const rows = entries.map((e) => `  ${JSON.stringify(e)},`).join("\n");
  return `// GENERATED by scripts/build-opening-book.ts from apps/web/public/openings/*.tsv (the \`openings\` seed). Do not edit.
// [eco, name, UCI moves from the initial position]; one entry per move sequence, the first in seed order.
export const OPENING_BOOK: readonly (readonly [eco: string, name: string, uci: string])[] = [
${rows}
];
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { entries, failures } = bookEntriesOf(readOpeningTsvs());
  writeFileSync(OUT, renderBookData(entries));
  console.log(`wrote ${entries.length} lines to ${path.relative(process.cwd(), OUT)}; ${failures.length} did not replay`);
  for (const f of failures) console.log(`  ${f}`);
}
