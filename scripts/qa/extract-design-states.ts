/**
 * Generates docs/qa/design-states.json (phase-01 plan §12.3, CT X8).
 *
 * For every v3 board assigned to a phase in docs/plan/allocation.md §4.2, it
 * reads the board's `.dc.html` from the design reference and records each enum
 * prop of its DCLogic `data-props` (the states a phase must reach). Boards with
 * no enum prop get one implicit state, "default". Superseded boards are skipped.
 *
 * The design reference (DR) is not in the repo, so run this once and again
 * whenever the design changes, then commit the JSON:
 *
 *   pnpm exec tsx scripts/qa/extract-design-states.ts --design <DR dir> [--out docs/qa/design-states.json]
 *
 * <DR dir> is the folder holding v2/*.dc.html's parent, e.g.
 * <scratchpad>/design-ref/project (the files are referenced as `v2/<Board>.dc.html`).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

export type BoardStates = {
  board: string;
  file: string;
  title: string;
  device: string;
  phase: number;
  feature: string;
  /** Enum props and their options; `{ state: ["default"] }` for boards without one. */
  props: Record<string, string[]>;
  implicit?: true;
};

export type DesignStates = {
  $comment: string;
  source: string;
  boards: BoardStates[];
};

type AllocationRow = { file: string; title: string; device: string; phase: string; feature: string };

/** Rows of allocation.md §4.2: `| # | \`v2/X.dc.html\` | title | device | page | **P1** | feature | states |`. */
export function parseAllocation(markdown: string): AllocationRow[] {
  const rows: AllocationRow[] = [];
  for (const line of markdown.split("\n")) {
    if (!/^\| \d+ \| `/.test(line)) continue;
    const cells = line.split("|").map((c) => c.trim());
    // ["", "#", "`file`", title, device, page, "**P1**", feature, states, ""]
    const file = cells[2]?.replace(/`/g, "") ?? "";
    const phase = (cells[6] ?? "").replace(/\*/g, "");
    rows.push({ file, title: cells[3] ?? "", device: cells[4] ?? "", phase, feature: cells[7] ?? "" });
  }
  return rows;
}

function decodeEntities(s: string): string {
  return s
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

/** Enum props of a board's DCLogic `data-props` attribute. */
export function enumProps(html: string): Record<string, string[]> {
  const props: Record<string, string[]> = {};
  for (const m of html.matchAll(/data-props=(?:'([^']*)'|"([^"]*)")/g)) {
    const raw = decodeEntities(m[1] ?? m[2] ?? "");
    let parsed: Record<string, { editor?: string; options?: unknown[] }>;
    try {
      parsed = JSON.parse(raw);
    } catch {
      continue;
    }
    for (const [name, spec] of Object.entries(parsed)) {
      if (name.startsWith("$") || spec?.editor !== "enum" || !Array.isArray(spec.options)) continue;
      props[name] = spec.options.map(String);
    }
  }
  return props;
}

export function buildDesignStates(allocation: string, readBoard: (file: string) => string | null): DesignStates {
  const boards: BoardStates[] = [];
  for (const row of parseAllocation(allocation)) {
    const phase = /^P(\d+)$/.exec(row.phase);
    if (!phase) continue; // superseded
    const html = readBoard(row.file);
    if (html === null) throw new Error(`design reference is missing ${row.file}`);
    const props = enumProps(html);
    const board = path.basename(row.file).replace(/\.dc\.html$/, "");
    const implicit = Object.keys(props).length === 0;
    boards.push({
      board,
      file: row.file,
      title: row.title,
      device: row.device,
      phase: Number(phase[1]),
      feature: row.feature,
      props: implicit ? { state: ["default"] } : props,
      ...(implicit ? { implicit: true as const } : {}),
    });
  }
  boards.sort((a, b) => a.phase - b.phase || a.board.localeCompare(b.board));
  return {
    $comment:
      "Generated by scripts/qa/extract-design-states.ts from the .dc.html boards and docs/plan/allocation.md §4.2. Do not edit by hand; record reviewed exceptions in design-states.overrides.json.",
    source: "design-ref/project/v2 (Claude Design export, not in the repo)",
    boards,
  };
}

function main() {
  const args = process.argv.slice(2);
  const arg = (name: string) => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const design = arg("--design") ?? process.env.DESIGN_REF_DIR;
  if (!design) {
    console.error("usage: extract-design-states.ts --design <dir containing v2/> [--out docs/qa/design-states.json]");
    process.exit(2);
  }
  const out = path.resolve(ROOT, arg("--out") ?? "docs/qa/design-states.json");
  const allocation = readFileSync(path.join(ROOT, "docs/plan/allocation.md"), "utf8");
  const manifest = buildDesignStates(allocation, (file) => {
    const p = path.join(design, file);
    return existsSync(p) ? readFileSync(p, "utf8") : null;
  });
  writeFileSync(out, JSON.stringify(manifest, null, 2) + "\n");
  const states = manifest.boards.reduce((n, b) => n + Object.values(b.props).reduce((m, o) => m + o.length, 0), 0);
  console.log(`design-states: ${manifest.boards.length} boards, ${states} states → ${path.relative(ROOT, out)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
